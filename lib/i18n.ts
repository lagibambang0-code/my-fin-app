type RecursiveStringRecord<T> = {
  [K in keyof T]: T[K] extends string ? string : RecursiveStringRecord<T[K]>
}
export type TranslationDictionary = RecursiveStringRecord<typeof TRANSLATIONS.en>

const STORAGE_KEY = 'dompetku:language'
export const DEFAULT_LOCALE: SupportedLocale = 'en'

/** Dapatkan bahasa aktif dari IndexedDB (atau localStorage fallback). */
export async function getAppLanguage(): Promise<SupportedLocale> {
  if (typeof window !== 'undefined') {
    const local = localStorage.getItem(STORAGE_KEY)
    if (local && isSupportedLocale(local)) return local
  }
  try {
    await initDB()
    const setting = await getSettingByKey('app_language')
    if (setting?.ZDATA && isSupportedLocale(setting.ZDATA)) {
      return setting.ZDATA
    }
  } catch {
    // fallback default
  }
  return DEFAULT_LOCALE
}

/** Check if a given language code is registered in SUPPORTED_LANGUAGES. */
export function isSupportedLocale(code: string): code is SupportedLocale {
  return SUPPORTED_LANGUAGES.some((l) => l.code === code)
}

/** Simpan bahasa aktif ke database IndexedDB dan localStorage secara permanen. */
export async function setAppLanguage(locale: SupportedLocale): Promise<void> {
  if (typeof window !== 'undefined') {
    localStorage.setItem(STORAGE_KEY, locale)
  }
  try {
    await initDB()
    await setSetting('app_language', locale)
  } catch (err) {
    console.error('Failed to persist language setting:', err)
  }
}
